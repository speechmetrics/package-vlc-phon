#!/usr/bin/env bash
# Regenerate the plug-in keep/remove lists from a VLC release (macOS only).
#
# Usage: seed-lists.sh <vlc-version> <out-dir>
#
# Writes <out-dir>/{windows,macos}-{keep,remove}.txt in the same format as
# lists/, ready to compare and copy. Windows lists come from the plug-in
# category folders. Each Mac plug-in takes the category of the Windows
# plug-in with the same base name, or its row in lists/macos-only.tsv.
# Mac plug-ins found in neither are written to <out-dir>/macos-unmatched.txt:
# add them to lists/macos-only.tsv and re-run. Non-universal Mac plug-ins
# are left out: package-macos.sh removes them by rule.
#
# Also refreshes licenses/{COPYING,AUTHORS}.txt from the Windows release,
# because the macOS disk image carries no licence files.
set -euo pipefail
source "$(dirname "$0")/lib.sh"

KEEP_CATEGORIES="access demux codec packetizer audio_output audio_filter audio_mixer video_output video_chroma video_filter stream_filter misc text_renderer spu meta_engine logger d3d9 d3d11"
REMOVE_CATEGORIES="gui control lua services_discovery stream_out access_output mux visualization keystore video_splitter stream_extractor"

v="$1"
out="$2"
here="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$out"
work=$(mktemp -d)
mnt="$work/mnt"
trap 'hdiutil detach -quiet "$mnt" 2>/dev/null || true; rm -rf "$work"' EXIT

dl="${DOWNLOAD_DIR:-$here/../build/dl}"
win_zip=$(fetch_vlc "$v" "win64/vlc-$v-win64.zip" "$dl")
dmg=$(fetch_vlc "$v" "macosx/vlc-$v-universal.dmg" "$dl")

# category <TAB> plug-in base name, from the Windows release
unzip -Z1 "$win_zip" \
    | sed -n "s#^vlc-$v/plugins/\([^/]*\)/\([^/]*\)\.dll\$#\1	\2#p" \
    | sort -u > "$work/win.tsv"

unzip -p "$win_zip" "vlc-$v/COPYING.txt" > "$here/../licenses/COPYING.txt"
unzip -p "$win_zip" "vlc-$v/AUTHORS.txt" > "$here/../licenses/AUTHORS.txt"

classify() {
    case " $KEEP_CATEGORIES " in *" $1 "*) echo keep; return ;; esac
    case " $REMOVE_CATEGORIES " in *" $1 "*) echo remove; return ;; esac
    echo unknown
}

: > "$work/windows-keep"
: > "$work/windows-remove"
while IFS= read -r c; do
    case $(classify "$c") in
        keep) echo "$c" >> "$work/windows-keep" ;;
        remove) echo "$c" >> "$work/windows-remove" ;;
        *) echo "unknown category: $c" >&2; exit 1 ;;
    esac
done < <(cut -f1 "$work/win.tsv" | sort -u)

hdiutil attach -nobrowse -readonly -mountpoint "$mnt" "$dmg" >/dev/null
: > "$work/macos-keep.tsv"
: > "$work/macos-remove.tsv"
: > "$out/macos-unmatched.txt"
for f in "$mnt"/VLC.app/Contents/MacOS/plugins/*.dylib; do
    name=$(basename "$f")
    archs=" $(lipo -archs "$f") "
    [[ "$archs" == *" arm64 "* && "$archs" == *" x86_64 "* ]] || continue
    c=$(awk -F'\t' -v n="${name%.dylib}" '$2 == n { print $1 }' "$work/win.tsv")
    if [ -n "$c" ]; then
        action=$(classify "$c")
    else
        row=$(awk -F'\t' -v n="$name" '!/^#/ && $2 == n { print $1 "\t" $3 }' "$here/../lists/macos-only.tsv")
        if [ -z "$row" ]; then
            echo "$name" >> "$out/macos-unmatched.txt"
            continue
        fi
        c=${row%%	*}
        action=${row#*	}
    fi
    printf '%s\t%s\n' "$c" "$name" >> "$work/macos-$action.tsv"
done

header() {
    printf '# macOS plug-ins to %s, grouped by VLC module category.\n' "$1"
    printf '# Generated by scripts/seed-lists.sh from VLC %s; Mac-only plug-ins\n' "$v"
    printf '# are placed by lists/macos-only.tsv. Non-universal plug-ins are\n'
    printf '# removed by rule in package-macos.sh and are not listed.\n'
}
for action in keep remove; do
    header "$action" > "$work/header"
    "$here/format-list.sh" "$work/header" "$work/macos-$action.tsv" > "$out/macos-$action.txt"
done

{
    printf '# Windows plug-in categories (folders under plugins/) to keep.\n'
    printf "# Phon plays local files through vlcj's callback video surface.\n\n"
    cat "$work/windows-keep"
} > "$out/windows-keep.txt"
{
    printf '# Windows plug-in categories (folders under plugins/) Phon cannot use:\n'
    printf '# interfaces, remote control, scripting, network discovery, streaming\n'
    printf '# and recording output, visualizations and password storage.\n\n'
    cat "$work/windows-remove"
} > "$out/windows-remove.txt"

if [ -s "$out/macos-unmatched.txt" ]; then
    echo "Mac plug-ins to place in lists/macos-only.tsv:" >&2
    cat "$out/macos-unmatched.txt" >&2
fi
